package comecocos;

public class Comecocos {
	private int x;
	private int y;
	
	public Comecocos() {
		this.x = 1;
		this.y = 1;
	}

	public int getX() {
		return x;
	}

	public void setX(int x) {
		this.x = x;
	}

	public int getY() {
		return y;
	}

	public void setY(int y) {
		this.y = y;
	}
	
	
}

